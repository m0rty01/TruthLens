function generateTimeline(days: number, baseMentions: number) {
  const entries = [];
  for (let i = days; i >= 0; i--) {
    const date = new Date();
    date.setDate(date.getDate() - i);
    entries.push({
      date: date.toISOString().split("T")[0],
      mentions: Math.max(0, baseMentions + Math.floor(Math.random() * baseMentions * 0.5 - baseMentions * 0.25)),
      sentiment: parseFloat((Math.random() * 2 - 1).toFixed(2)),
    });
  }
  return entries;
}

